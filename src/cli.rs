use clap::{Parser, Subcommand};
use std::path::PathBuf;

#[derive(Parser, Debug)]
#[command(
    name = "web-shield",
    version,
    about = "Passive web security scanner with local LLM explanations",
    long_about = "Fetches headers, cookies, CSP and tech fingerprints in one request.\nUses a local Ollama model to produce plain-English risk summaries and copy-paste fixes.\nRetro terminal UI with phosphor-green ASCII aesthetics.",
    after_help = "Examples:\n  web-shield scan https://example.com\n  web-shield scan https://example.com https://test.com --max-concurrent 5\n  web-shield scan https://example.com --model llama3.2 --output report.md\n  web-shield scan sitemap.xml --model llama3.2\n  web-shield scan urls.txt --max-concurrent 10\n  web-shield interactive --url https://example.com\n\nInteractive keys:\n  Tab/h/l      Switch tabs\n  j/k/up/down  Navigate findings\n  c            Open chat about selected finding (Findings tab)\n  Enter        Send chat message\n  ?            Help\n  q            Quit"
)]
pub struct Args {
    #[command(subcommand)]
    pub command: Commands,
}

#[derive(Subcommand, Debug)]
pub enum Commands {
    /// Perform a passive security scan on one or more target URLs (parallel when >1)
    Scan(ScanCmd),
    /// Analyze a previously saved JSON scan report with an LLM
    Analyze(AnalyzeCmd),
    /// Launch the interactive Ratatui terminal explorer
    Interactive(InteractiveCmd),
}

#[derive(Parser, Debug)]
pub struct ScanCmd {
    /// One or more targets to scan. Each target can be:
    /// - A direct URL (http:// or https://)
    /// - Path to a sitemap.xml (local file or remote URL) — automatically extracts all <loc> URLs
    /// - Path to a plain text file with one URL per line (comments with # supported)
    ///
    /// Multiple targets and mixed types are supported. Parallel scanning is used when total
    /// resolved URLs > 1.
    #[arg(index = 1, required = true, value_parser = validate_target, num_args = 1..)]
    pub urls: Vec<String>,

    /// Ollama model name to use for explanation (must be available locally)
    #[arg(short, long)]
    pub model: Option<String>,

    /// Output path (supports .md, .json, .sarif). Omitting prints retro terminal UI.
    #[arg(short, long)]
    pub output: Option<String>,

    /// Path to custom YAML rule file (defaults to embedded rules)
    #[arg(short, long, value_name = "RULES_YAML")]
    pub rules: Option<PathBuf>,

    /// Maximum number of concurrent HTTP requests (shared rate limiter via Semaphore).
    /// Default is 5.
    #[arg(long, default_value_t = 5)]
    pub max_concurrent: usize,

    /// CI mode: no colors, no TUI, SARIF-friendly output and proper exit codes
    #[arg(long)]
    pub ci: bool,
}

#[derive(Parser, Debug)]
pub struct AnalyzeCmd {
    /// Path to a JSON scan report generated by a previous scan
    #[arg(index = 1, required = true)]
    pub report: PathBuf,

    /// Ollama model to use for generating explanations
    #[arg(short, long, default_value = "llama3.2")]
    pub model: String,

    /// Output markdown file path
    #[arg(short, long, default_value = "web-shield-report.md")]
    pub output: PathBuf,
}

#[derive(Parser, Debug)]
pub struct InteractiveCmd {
    /// Optional URL to scan before launching the interactive explorer
    #[arg(short, long)]
    pub url: Option<String>,

    /// Ollama model to use if a scan is performed
    #[arg(short, long, default_value = "llama3.2")]
    pub model: String,
}

fn validate_target(s: &str) -> Result<String, String> {
    if s.starts_with("http://") || s.starts_with("https://") || std::path::Path::new(s).exists() {
        Ok(s.to_string())
    } else {
        Err("Target must be a valid http/https URL or an existing local file path (sitemap.xml or URL list)".to_string())
    }
}
