//! Report formatting for terminal, Markdown, and SARIF.
//!
//! `print_terminal` produces a retro-CRT styled output using phosphor-green
//! ANSI colors, ASCII box drawing, and clear severity labels. All other
//! formats are pure data transformations with no side effects.

use crate::types::{Finding, ScanReport, Severity};
use serde_json::json;

/// Prints a retro-terminal styled security report using ASCII box art
/// and phosphor-green/amber/red ANSI colors. Matches the project's
/// visual direction exactly (monospace, scanline-friendly, no rounded
/// modern UI elements).
pub fn print_terminal(report: &ScanReport) {
    // Reset and set phosphor green
    println!("\x1b[0;32m");
    println!("┌──────────────────────────────────────────────────────────────────────────────┐");
    println!("│                          WEB SHIELD SCAN REPORT v0.1.0                       │");
    println!("├──────────────────────────────────────────────────────────────────────────────┤");
    println!("│ URL      : {:<66} │", report.url);
    println!(
        "│ Score    : {:<3}/100 {:<51} │",
        report.score,
        score_indicator(report.score)
    );
    println!(
        "│ Tech     : {:<66} │",
        if report.tech.is_empty() {
            "none detected"
        } else {
            &report.tech.join(", ")
        }
    );
    println!("│ Findings : {:<66} │", report.findings.len());
    println!("└──────────────────────────────────────────────────────────────────────────────┘");
    println!("\x1b[0m");

    if report.findings.is_empty() {
        println!("\x1b[0;32m[+] No issues found. Site appears secure.\x1b[0m\n");
        return;
    }

    println!("\x1b[0;32mFINDINGS\x1b[0m\n");

    for finding in &report.findings {
        let color = match finding.severity {
            Severity::Critical | Severity::High => "\x1b[0;31m",
            Severity::Medium => "\x1b[0;33m",
            _ => "\x1b[0;32m",
        };
        println!(
            "{}[{}]\x1b[0;32m {}\x1b[0m",
            color,
            severity_label(&finding.severity),
            finding.title
        );
        println!("    ID          : {}", finding.id);
        println!("    Description : {}", finding.description);
        println!("    \x1b[0;32mRecommendation:\x1b[0m");
        for line in finding.recommendation.lines() {
            if !line.trim().is_empty() {
                println!("      {}", line);
            }
        }
        println!();
    }

    println!("\x1b[0;32mRun with --output report.md for full LLM analysis.\x1b[0m");
}

/// Returns a Markdown report containing the scan summary, per-finding
/// details, and the LLM-generated plain-English explanation.
pub fn to_markdown(report: &ScanReport, explanation: &str) -> String {
    let mut md = String::with_capacity(4096);

    md.push_str("# Web Shield Security Report\n\n");
    md.push_str("**URL:** ");
    md.push_str(&report.url);
    md.push_str("\n**Risk Score:** ");
    md.push_str(&report.score.to_string());
    md.push_str("/100\n**Technologies:** ");
    md.push_str(if report.tech.is_empty() {
        "none detected"
    } else {
        &report.tech.join(", ")
    });
    md.push_str("\n\n");

    md.push_str("## Findings\n\n");
    for finding in &report.findings {
        md.push_str(&format!(
            "### [{}] {}\n\n",
            severity_label(&finding.severity),
            finding.title
        ));
        md.push_str(&format!("**ID:** `{}`\n\n", finding.id));
        md.push_str(&finding.description);
        md.push_str("\n\n**Recommended fix:**\n\n");
        md.push_str("```nginx\n");
        md.push_str(&finding.recommendation);
        md.push_str("\n```\n\n");
    }

    md.push_str("## LLM Analysis (");
    md.push_str(if report.score >= 75 { "low risk" } else { "action required" });
    md.push_str(")\n\n");
    md.push_str(explanation);
    md.push_str("\n\n---\n\n");
    md.push_str("*Report generated by [Web Shield](https://github.com/web-shield/web-shield). ");
    md.push_str("Local-only, no data leaves your machine.*");

    md
}

/// Returns a SARIF 2.1.0 JSON document suitable for CI/CD ingestion
/// (GitHub Advanced Security, GitLab, etc.).
pub fn to_sarif(report: &ScanReport) -> String {
    let results: Vec<_> = report
        .findings
        .iter()
        .map(|f| {
            let level = match f.severity {
                Severity::Critical | Severity::High => "error",
                Severity::Medium => "warning",
                _ => "note",
            };
            json!({
                "ruleId": f.id,
                "level": level,
                "message": {
                    "text": format!("{} - {}", f.title, f.description)
                },
                "locations": [{
                    "physicalLocation": {
                        "uri": report.url,
                        "region": {
                            "startLine": 1
                        }
                    }
                }],
                "properties": {
                    "severity": severity_label(&f.severity),
                    "recommendation": f.recommendation
                }
            })
        })
        .collect();

    let sarif = json!({
        "$schema": "https://json.schemastore.org/sarif-2.1.0-rtm.5.json",
        "version": "2.1.0",
        "runs": [{
            "tool": {
                "driver": {
                    "name": "web-shield",
                    "version": "0.1.0",
                    "informationUri": "https://github.com/web-shield/web-shield",
                    "rules": []
                }
            },
            "results": results,
            "invocations": [{
                "executionSuccessful": true
            }]
        }]
    });

    serde_json::to_string_pretty(&sarif).unwrap_or_else(|_| r#"{"version":"2.1.0","runs":[]}"#.to_string())
}

fn severity_label(s: &Severity) -> &'static str {
    match s {
        Severity::Critical => "CRITICAL",
        Severity::High => "HIGH",
        Severity::Medium => "MEDIUM",
        Severity::Low => "LOW",
        Severity::Info => "INFO",
    }
}

fn score_indicator(score: u8) -> &'static str {
    if score >= 85 {
        "\x1b[0;32m[GOOD]\x1b[0m"
    } else if score >= 60 {
        "\x1b[0;33m[MEDIUM]\x1b[0m"
    } else {
        "\x1b[0;31m[HIGH RISK]\x1b[0m"
    }
}
